// The atlas of who lived where: what a living scene reads to know what could stand at a place and a
// time. For each stage of geological time it holds a list for each patch of land, and each taxon on a list
// says how sure that is, in tiers. It holds no plant and no animal: those are generated from it.

/** How directly a taxon's being here rests on evidence. */
export const TIER = { here: 0, region: 1, standin: 2 } as const;
export type Tier = (typeof TIER)[keyof typeof TIER];

export const TIER_WORDS: Record<Tier, string> = {
  0: 'Recorded here',
  1: 'Recorded in the region',
  2: 'A stand-in: nothing like it is recorded near here',
};

/** A claimed size: a measured one has lo equal to hi, and a clade's stands for any member not measured. */
export interface AtlasSize {
  lo: number;
  hi: number;
  /** the node of the tree whose claim it is, and its name */
  from: string;
  own: boolean;
}

export interface AtlasTaxon {
  /** its number in the Paleobiology Database */
  no: number;
  /** a record that adopts it, if one does */
  id?: string;
  label: string;
  rank: string;
  /** whose form it is drawn with: a key in the forms file, and the node of the tree it comes from */
  form: string;
  form_from: string;
  form_label: string;
  /** whether that node is this taxon: if not, nobody has written its own yet */
  own: boolean;
  length?: AtlasSize;
  hip?: AtlasSize;
  height?: AtlasSize;
  mass?: AtlasSize;
  posture?: string;
  diet?: string;
  habit?: string;
  /** the rows of this stage that name it or a taxon below it, worldwide */
  rows: number;
  /** the oldest and youngest ages those rows allow, in Ma */
  span: [number, number];
  /** drawn as this clade because nothing nearer is known: not a claim that this clade lived here */
  standin?: boolean;
}

/** The grid an atlas's lists are on: nodes are boxes, from the north-west. */
export interface AtlasGrid {
  step: number;
  nx: number;
  ny: number;
}

export interface AtlasBinRef {
  /** astronomical years */
  from: number;
  to: number;
  /** the moment a scene of this stage is written for */
  slice: number;
  name: string;
  file: string;
  /** rows that fall in it, and patches of land that have a list */
  rows: number;
  nodes: number;
}

export interface AtlasIndex {
  format: 'lightworld-atlas@1';
  title: string;
  description?: string;
  source: string;
  sourceRecord?: import('./records.ts').SourceRecord;
  grid: AtlasGrid;
  /** how the tiers are drawn: the distances, in km over land */
  here_km: number;
  region_km: number;
  /** the file of whole forms, by key */
  forms: string;
  /** what scenes are generated by, and how */
  generator: { id: string; version: number; params: Record<string, unknown> };
  bins: AtlasBinRef[];
  /** where to go to see a record's taxon: the file of them */
  where: string;
  /** how far the world's forms reach, as a summary */
  coverage: { taxa: number; own_form: number; inherited_form: number; no_form: number; rows_drawable: number; rows_total: number };
}

/** One stage. `nodes` maps a patch to flat fours: taxon (an index in `taxa`), weight 0–255, tier, and km to the nearest of its rows, in tens. */
export interface AtlasBin {
  format: 'lightworld-atlas-bin@1';
  from: number;
  to: number;
  slice: number;
  name: string;
  taxa: AtlasTaxon[];
  nodes: Record<string, number[]>;
}

/** Where the most fossils of a taxon or anything below it are, and when: to go and see it. */
export interface AtlasWhere {
  /** the slice of the stage, and a place on the globe of that time */
  t: number;
  lat: number;
  lon: number;
  rows: number;
}

export const atlasKey = (g: AtlasGrid, lat: number, lon: number): number => {
  const row = Math.max(0, Math.min(g.ny - 1, Math.floor((90 - lat) / g.step)));
  const col = ((Math.floor((lon + 180) / g.step) % g.nx) + g.nx) % g.nx;
  return row * g.nx + col;
};

export interface AtlasEntry {
  taxon: AtlasTaxon;
  weight: number;
  tier: Tier;
  /** to the nearest of its rows */
  km: number;
}

/** Whether a stage has a list for a place: it has if there is land there, even with nothing on the list. */
export const atlasHasLand = (bin: AtlasBin, grid: AtlasGrid, lat: number, lon: number): boolean => bin.nodes[String(atlasKey(grid, lat, lon))] !== undefined;

/** The list for a place in a stage, heaviest first in each kind, as the file holds it. */
export function atlasList(bin: AtlasBin, grid: AtlasGrid, lat: number, lon: number): AtlasEntry[] {
  const flat = bin.nodes[String(atlasKey(grid, lat, lon))];
  if (!flat) return [];
  const out: AtlasEntry[] = [];
  for (let i = 0; i + 3 < flat.length; i += 4) out.push({ taxon: bin.taxa[flat[i]], weight: flat[i + 1], tier: flat[i + 2] as Tier, km: flat[i + 3] * 10 });
  return out;
}

// The sea's atlas (tools/world/src/build/sea.ts): the same stages, patches and tiers over the sea, of genera with no
// forms, since the sea's great groups have none in the world yet. Its lists say what lived where; they draw nothing.

/** A genus on a list of the sea, and the class or phylum the database puts it in. */
export interface SeaTaxon {
  no: number;
  label: string;
  rank: string;
  group: string;
  /** the rows of this stage that name it or a taxon below it, worldwide */
  rows: number;
  /** the oldest and youngest ages those rows allow, in Ma */
  span: [number, number];
  /** listed because nothing is recorded near: the stage's commonest of a like belt of latitude */
  standin?: boolean;
}

/** One stage of the sea: `nodes` maps a patch of sea to flat fours, as the land's do. */
export interface SeaBin {
  format: 'lightworld-sea-bin@1';
  from: number;
  to: number;
  slice: number;
  name: string;
  taxa: SeaTaxon[];
  nodes: Record<string, number[]>;
}

export interface SeaIndex {
  format: 'lightworld-sea-atlas@1';
  title: string;
  description?: string;
  source: string;
  sourceRecord?: import('./records.ts').SourceRecord;
  grid: AtlasGrid;
  /** how the tiers are drawn: the distances, in km over the sea */
  here_km: number;
  region_km: number;
  bins: AtlasBinRef[];
}

/** The list for a place of the sea in a stage; undefined where the stage has no sea there. */
export function seaList(bin: SeaBin, grid: AtlasGrid, lat: number, lon: number): { taxon: SeaTaxon; weight: number; tier: Tier; km: number }[] | undefined {
  const flat = bin.nodes[String(atlasKey(grid, lat, lon))];
  if (!flat) return undefined;
  const out: { taxon: SeaTaxon; weight: number; tier: Tier; km: number }[] = [];
  for (let i = 0; i + 3 < flat.length; i += 4) out.push({ taxon: bin.taxa[flat[i]], weight: flat[i + 1], tier: flat[i + 2] as Tier, km: flat[i + 3] * 10 });
  return out;
}
