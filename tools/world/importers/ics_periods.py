"""Generate world/periods/ics-2020-03.yaml from the palaeoverse GTS2020 table.

    python ics_periods.py <palaeoverse>/data/GTS2020.rda > world/periods/ics-2020-03.yaml

The table (palaeoverse/palaeoverse, data/GTS2020.rda) was compiled from the ICS
International Chronostratigraphic Chart v2020/03, including its standard colours.
Only Phanerozoic intervals are kept. Requires `pip install rdata`.
"""
import re
import sys

import rdata

RANKS = ['eon', 'era', 'period', 'sub-system', 'epoch', 'sub-epoch', 'stage']
PARENT_RANKS = ['eon', 'era', 'period', 'epoch', 'stage']


def slug(name):
    return re.sub(r'[^a-z0-9]+', '-', name.lower()).strip('-')


def num(x):
    s = f'{x:.4f}'.rstrip('0').rstrip('.')
    return s


def main(path):
    df = rdata.conversion.convert(rdata.parser.parse_file(path))['GTS2020']
    df = df[df['max_ma'] <= 541.0 + 1e-9]
    rows = [r for r in df.to_dict('records')]
    rows.sort(key=lambda r: (RANKS.index(r['rank']), -r['max_ma']))
    # A few names are used at two ranks (the Pridoli is an epoch and its only stage);
    # the lower-ranked one gets the rank as a suffix.
    seen = set()
    for r in rows:
        r['id'] = slug(r['interval_name'])
        if r['id'] in seen:
            r['id'] = f"{r['id']}-{slug(r['rank'])}"
        seen.add(r['id'])
    out = [
        '# ICS International Chronostratigraphic Chart v2020/03, Phanerozoic intervals.',
        '# Generated by tools/world/importers/ics_periods.py from the palaeoverse GTS2020 table',
        '# (palaeoverse/palaeoverse@d01a8955824c41c0fa45acd7337eb3bb46d9044d, data/GTS2020.rda),',
        '# which was compiled from the chart PDF. Colours are the chart\'s standard RGB codes.',
        '# Boundary uncertainties are not included in that table.',
        'source: ics-chart-2020-03',
        'periods:',
    ]
    for r in rows:
        parent = None
        for pr in PARENT_RANKS[:PARENT_RANKS.index(r['rank']) if r['rank'] in PARENT_RANKS else len(PARENT_RANKS)][::-1]:
            cands = [p for p in rows if p['rank'] == pr and p['max_ma'] >= r['max_ma'] - 1e-9 and p['min_ma'] <= r['min_ma'] + 1e-9 and p is not r]
            if cands:
                parent = cands[0]
                break
        out.append(f'  - id: ics/{r["id"]}')
        out.append(f'    name: {r["interval_name"]}')
        out.append(f'    rank: {r["rank"]}')
        out.append(f'    start: {{ ma: {num(r["max_ma"])} }}')
        out.append(f'    end: {{ ma: {num(r["min_ma"])} }}')
        out.append(f'    color: "{r["colour"].upper()}"')
        if parent is not None:
            out.append(f'    parent: ics/{parent["id"]}')
    print('\n'.join(out))


if __name__ == '__main__':
    main(sys.argv[1])
