"""Write the ICS chart's Phanerozoic intervals as period entities, one file each.

    python ics_periods.py <palaeoverse>/data/GTS2020.rda world/entities/periods/ics

The table (palaeoverse/palaeoverse, data/GTS2020.rda) was compiled from the ICS
International Chronostratigraphic Chart v2020/03, including its standard colours; it has
no boundary uncertainties. Each interval becomes an entity of kind period/<rank> whose
name, start and colour are claims citing the chart. Its end is the start of the next
interval of the same rank (a `before` relation with no lag), so each boundary is stated
once; an interval with no successor of its rank states its end, unless it is the youngest,
which still holds. Claims and relations whose keys start with "ics-" are rewritten on
re-import; any others in an existing file are kept. Requires `pip install rdata`.
"""
import os
import re
import sys

import rdata

RANKS = ['eon', 'era', 'period', 'sub-system', 'epoch', 'sub-epoch', 'stage']
KIND = {'eon': 'eon', 'era': 'era', 'period': 'period', 'sub-system': 'sub-period',
        'epoch': 'epoch', 'sub-epoch': 'sub-epoch', 'stage': 'stage'}
PARENT_RANKS = ['eon', 'era', 'period', 'epoch', 'stage']
SOURCE = 'src:ics-chart-2020-03'
OWN = 'ics-'


def slug(name):
    return re.sub(r'[^a-z0-9]+', '-', name.lower()).strip('-')


def num(x):
    return f'{x:.4f}'.rstrip('0').rstrip('.')


def kept_entries(text, section):
    """Raw text of the entries of a top-level block mapping whose keys are not ours."""
    out, cur, inside = [], None, False
    for line in text.splitlines(keepends=True):
        if not line.startswith(' ') and line.strip():
            inside = line.rstrip() == f'{section}:'
            cur = None
            continue
        if not inside:
            continue
        m = re.match(r'^  ([A-Za-z0-9_-]+):', line)
        if m:
            cur = None if m.group(1).startswith(OWN) else []
            if cur is not None:
                out.append(cur)
        if cur is not None:
            cur.append(line)
    return [''.join(e) for e in out]


def main(path, outdir):
    df = rdata.conversion.convert(rdata.parser.parse_file(path))['GTS2020']
    df = df[df['max_ma'] <= 541.0 + 1e-9]
    rows = [r for r in df.to_dict('records')]
    rows.sort(key=lambda r: (RANKS.index(r['rank']), -r['max_ma']))
    # A few names are used at two ranks (the Pridoli is an epoch and its only stage);
    # the lower-ranked one gets the rank as a suffix.
    seen = set()
    for r in rows:
        r['id'] = slug(r['interval_name'])
        if r['id'] in seen:
            r['id'] = f"{r['id']}-{slug(r['rank'])}"
        seen.add(r['id'])
    os.makedirs(outdir, exist_ok=True)
    for r in rows:
        parent = None
        for pr in [x for x in PARENT_RANKS if RANKS.index(x) < RANKS.index(r['rank'])][::-1]:
            cands = [p for p in rows if p['rank'] == pr and p['max_ma'] >= r['max_ma'] - 1e-9 and p['min_ma'] <= r['min_ma'] + 1e-9 and p is not r]
            if cands:
                parent = cands[0]
                break
        nxt = [p for p in rows if p['rank'] == r['rank'] and abs(p['max_ma'] - r['min_ma']) < 1e-9]
        rank = KIND[r['rank']]
        loc = f'{rank.capitalize()} {r["interval_name"]}'
        src = f'{{ ref: {SOURCE}, loc: "{loc}" }}'
        file = os.path.join(outdir, f'{r["id"]}.yaml')
        old = open(file, encoding='utf8').read() if os.path.exists(file) else ''
        claims = [
            f'  {OWN}name:\n    prop: name\n    value: {{ en: {r["interval_name"]} }}\n    source: {src}\n',
            f'  {OWN}start:\n    prop: start\n    value: {num(r["max_ma"])} Ma\n    source: {src}\n',
        ]
        if not nxt and r['min_ma'] > 0:
            claims.append(f'  {OWN}end:\n    prop: end\n    value: {num(r["min_ma"])} Ma\n    source: {src}\n')
        claims.append(f'  {OWN}color:\n    prop: color\n    value: "{r["colour"].upper()}"\n    source: {src}\n')
        relations = []
        if parent is not None:
            relations.append(f'  {OWN}part-of:\n    rel: part-of\n    to: ics/{parent["id"]}\n    source: {src}\n')
        if nxt:
            relations.append(f'  {OWN}next:\n    rel: before\n    to: ics/{nxt[0]["id"]}\n    lag: 0 yr\n    source: {src}\n')
        text = (
            '# Generated by tools/world/importers/ics_periods.py from the ICS chart v2020/03. Claims\n'
            '# and relations whose keys start with "ics-" are rewritten on re-import; others are kept.\n'
            f'id: ics/{r["id"]}\n'
            f'kind: period/{rank}\n'
            'author: machine:ics-periods\n'
            'claims:\n' + ''.join(claims + kept_entries(old, 'claims'))
        )
        relations += kept_entries(old, 'relations')
        if relations:
            text += 'relations:\n' + ''.join(relations)
        with open(file, 'w', encoding='utf8') as f:
            f.write(text)
    print(f'{len(rows)} periods written to {outdir}', file=sys.stderr)


if __name__ == '__main__':
    main(sys.argv[1], sys.argv[2])
